export function translate(
  language: AppLanguage,
  key: string,
  values: Record<string, string | number> = {}
) {
  const template =
    language === 'zh' ? (zh[key] ?? translateDynamicChinese(key)) : key;
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{{${name}}}`, String(value)),
    template
  );
}

export function translateExerciseName(language: AppLanguage, name: string) {
  return language === 'zh' ? (defaultExerciseTranslations[name] ?? name) : name;
}

function translateDynamicChinese(key: string) {
  const patterns: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [
      /^Use (\d+) characters or fewer\.$/,
      (match) => `请使用不超过 ${match[1]} 个字符。`
    ],
    [
      /^Weight must be (.+) kg or less\.$/,
      (match) => `重量不能超过 ${match[1]} kg。`
    ],
    [
      /^Repetitions must be (\d+) or fewer\.$/,
      (match) => `次数不能超过 ${match[1]}。`
    ],
    [/^Repetitions at (.+) kg$/, (match) => `${match[1]} kg 对应次数`],
    [
      /^Unsupported backup schema\. This app supports schema version (.+)\.$/,
      (match) => `不支持此备份架构。当前应用支持架构版本 ${match[1]}。`
    ],
    [
      /^The backup contains invalid (.+) records\.$/,
      (match) => `备份包含无效的 ${match[1]} 记录。`
    ],
    [
      /^The backup contains duplicate (.+) IDs\.$/,
      (match) => `备份包含重复的 ${match[1]} ID。`
    ]
  ];
  for (const [pattern, format] of patterns) {
    const match = key.match(pattern);
    if (match) return format(match);
  }
  return key;
}
